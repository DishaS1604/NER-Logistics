import streamlit as st

from core.risk import TYPE_LABEL
from views.common import fmt_time, get_state


def render():
    s = get_state()
    st.header("Risk alerts")
    st.caption("Alerts are generated by changes to reports, verification, and road status.")
    f = st.selectbox("Severity", ["all", "critical", "warning", "info"])
    shown = [a for a in s["alerts"] if f == "all" or a["severity"] == f]
    if not shown:
        st.info("No alerts.")
    for a in shown:
        with st.container(border=True):
            icon = {"critical": "🔴", "warning": "🟠", "info": "🔵"}[a["severity"]]
            st.markdown(f"{icon} **{a['title']}** · :gray[{fmt_time(a['time'])}]")
            loc = a["location"] + (f" · {TYPE_LABEL[a['incident_type']]}" if a.get("incident_type") else "")
            st.write(f"**Location:** {loc}")
            st.write(a["explanation"])
            st.write(f"**Recommended action:** {a['action']}")
